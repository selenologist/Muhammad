/* Appended to a generated TU by tools/gen_tables.sh (after melodee's generated
 * headers). Dumps every table this port needs, verbatim. */
static void putF(const char *name, const float *t, int n)
{
    int i;
    printf("static const float %s[%d] = {\n", name, n);
    for (i = 0; i < n; i++)
        printf("%s%.9ef%s", i % 6 ? "\t" : "    ", t[i], i == n-1 ? "" : ",", i % 6 == 5 ? "\n" : "");
    printf("%s};\n\n", (n-1) % 6 == 5 ? "" : "\n");
}
static void putU(const char *name, const uint32_t *t, int n)
{
    int i;
    printf("static const uint32_t %s[%d] = {\n", name, n);
    for (i = 0; i < n; i++)
        printf("%s%u%s", i % 8 ? "\t" : "    ", t[i], i == n-1 ? "" : ",", i % 8 == 7 ? "\n" : "");
    printf("%s};\n\n", (n-1) % 8 == 7 ? "" : "\n");
}
static void putU16(const char *name, const uint16_t *t, int n)
{
    int i;
    printf("static const uint16_t %s[%d] = {\n", name, n);
    for (i = 0; i < n; i++)
        printf("%s%u%s", i % 8 ? "\t" : "    ", t[i], i == n-1 ? "" : ",", i % 8 == 7 ? "\n" : "");
    printf("%s};\n\n", (n-1) % 8 == 7 ? "" : "\n");
}
int main(void)
{
    unsigned k, i;
    printf("/* GENERATED by tools/gen_tables.sh from the melodee firmware tables - do not edit.\n"
           " * Source: build/gen/melodee_tables.h + melodee_prophet_factory.h\n"
           " * (tools/gen_tables.sh), P5_OVERSAMPLE == 1 build. */\n"
           "#pragma once\n#include <cstdint>\n\n");
    printf("#define PW_FS %d\n#define PW_CTL %d\n#define PW_KEYTRACK_HALF_Q7 %d\n", FS, CTL, P5_KEYTRACK_HALF_Q7);
    printf("#define PW_FACTORY_N %u\n\n", (unsigned)P5_FACTORY_N);
    putU("PW_PITCH_OCT", PITCH_OCT, (int)(sizeof PITCH_OCT / sizeof *PITCH_OCT));
    putU("PW_ENV_LIN", ENV_LIN, 128);
    putU16("PW_ENV_EXP16", ENV_EXP, 128);
    putU("PW_P5_LFO_INC", P5_LFO_INC, 128);
    putF("PW_P5_AMOUNT", P5_AMOUNT, 128);
    putF("PW_P5_ENV_ATK", P5_ENV_ATK, 128);
    putF("PW_P5_ENV_EXP", P5_ENV_EXP, 128);
    putF("PW_P5_ENV_SSM", P5_ENV_SSM, 128);
    if (sizeof P5_TPT_G / sizeof *P5_TPT_G != 128u) return 2;   /* must be the OS==1 build */
    putF("PW_P5_TPT_G", P5_TPT_G, 128);
    putF("PW_P5_TANH", P5_TANH, 1025);
    putF("PW_P5_EXP2", P5_EXP2, 514);
    printf("/* Sequential's %u factory programs, raw 133-byte wire bytes each (unpacked\n"
           " * from P5_FPACK exactly as eng_prophet_test.c's p5_factory does) */\n", (unsigned)P5_FACTORY_N);
    printf("static const uint8_t PW_FACTORY_RAW[PW_FACTORY_N][133] = {\n");
    {
        p5_patch_t p;
        for (k = 0; k < P5_FACTORY_N; k++) {
            const uint8_t *b = P5_FPACK + k * P5_FACTORY_BYTES;
            uint32_t pos = 0;
            for (i = 0; i < 133u; i++) {
                uint32_t v = 0, j;
                for (j = 0; j < P5_FWIDTH[i]; j++, pos++) v |= (uint32_t)(b[pos >> 3] >> (pos & 7u) & 1u) << j;
                p.raw[i] = (uint8_t)(P5_FBASE[i] + v);
            }
            printf("    {");
            for (i = 0; i < 133u; i++) printf("%s0x%02X", i ? "," : "", p.raw[i]);
            printf("}%s\n", k == P5_FACTORY_N-1 ? "" : ",");
        }
    }
    printf("};\n");
    return 0;
}
