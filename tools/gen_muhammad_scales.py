# Generate src/p5_stock_scales.hpp from the melodee firmware's scale tables
# (firmware/src/scales.h — itself generated from assets/scales/catalog.json)
# plus the Wendy Carlos scales (alpha/beta/gamma: divisions of the perfect
# fifth by 9/11/20, octave kept as the wrap; the harmonic scale: 16th..32nd
# partials skipping 23,25,29,31 — values verified against wendycarlos.com and
# Wikipedia "Wendy Carlos scales", Oct 2026).
#
# Semantics per entry:
#   degrees   = number of scale tones including the unison (melodee convention)
#   p[]       = p[0]=0, p[1..degrees-1] degrees, p[degrees]=period (usually 1200)
#   mask      = chromatic key positions of the degrees (walk=0); for micros
#               without an explicit melodee mask, positions are derived by
#               rounding cents/100 with collision shifting
#   walk      = degrees>12: nothing to quantize, every key advances one degree
#               (melodee's ALL mode); <=12 with a mask quantizes to nearest
import re, sys

SRC = "/home/user/build/melodee/firmware/src/scales.h"
OUT = "src/p5_stock_scales.hpp"

text = open(SRC).read()

def arr(name, kind=None):
    m = re.search("static const [^;]*?\\b" + name + "\\s*(?:\\[[^\\]]*\\])?\\s*=\\s*\\{(.*?)\\};", text, re.S)
    if not m: raise SystemExit("missing " + name)
    return [x.strip() for x in m.group(1).split(",") if x.strip()]

titles = [t.strip('"') for t in arr("SCALE_TITLE")]
codes  = [t.strip('"') for t in arr("N_SCALE")]
degrees = [int(x) for x in arr("SCALE_DEGREES")]
family  = [int(x) for x in arr("SCALE_FAMILY")]
masks   = [int(x, 16) for x in arr("SCALE_MASK")]
pitches = {n: [int(v) for v in arr("SCALE_P" + n[1:])] for n in
           ["P16","P17","P18","P19","P20","P21","P22","P23","P24","P25","P26","P27","P28","P29",
            "P30","P31","P32","P33","P34","P35","P36","P37","P38","P39","P40","P41","P42","P43",
            "P44","P45","P46","P47","P48","P49","P50","P51","P52","P53","P54","P55","P56","P57",
            "P58","P59","P60","P61","P62","P63","P64","P65","P66","P67","P68","P69"]}

micro = {code: (int(n), pitches[p.replace("SCALE_", "")]) for n, p, code in
           re.findall(r"\{\s*(\d+),\s*(SCALE_P\d+)\},?\s*/\*\s*([\w/-]+)\s*\*/", text)}

FAM = {0:"WEST",1:"EDO",2:"JUST",3:"HARM",4:"HIST",5:"WORLD",6:"BP",7:"MAQAM"}

def derive_positions(p, degrees_incl_unison):
    pos = []
    for d in range(1, degrees_incl_unison):          # unison is position 0
        slot = int(p[d] / 100.0 + 0.5) % 12
        while slot in pos: slot = (slot + 1) % 12
        pos.append(slot)
    if 0 in pos:                                     # unison owns 0; shift clash
        pos = [s if s != 0 else 1 for s in pos]
        for i, s in enumerate(pos):                  # re-collide check after shift
            if pos.count(s) > 1 and s != 0: pos[i] = (s + 1) % 12
    m = 1
    for d, s in zip(range(1, degrees_incl_unison), pos): m |= 1 << s
    return m

entries = []   # (title, group, degrees, mask, walk, [p cents float])
for i in range(70):
    title, code = titles[i], codes[i]
    if i < 16:                                       # legacy mask scales (ET)
        mask = masks[i]; deg = degrees[i]
        pos = [b for b in range(12) if mask >> b & 1]
        assert len(pos) == deg, (code, mask, deg)
        p = [b * 100.0 for b in pos] + [1200.0]
        walk = False
    else:
        deg, p_raw = micro[code]
        p = [c / 100.0 for c in p_raw]
        assert len(p) == deg + 1 and abs(p[0]) < 1e-6, (code, deg, len(p))
        walk = deg > 12
        mask = 0 if walk else derive_positions(p, deg)
    if not walk:
        assert bin(mask).count("1") == deg, (code, deg, hex(mask))
    entries.append((title, FAM[family[i]], deg, mask, walk, p))

# --- Wendy Carlos -------------------------------------------------------------
def steps(s, period=1200.0):
    v = 0.0; out = [0.0]
    while True:
        v += s
        if v >= period - 1e-6: break
        out.append(round(v, 4))
    out.append(period)
    return out
FIFTH = 702.0
carlos = [
    ("Alpha (Carlos)",  steps(FIFTH / 9)),
    ("Beta (Carlos)",   steps(FIFTH / 11)),
    ("Gamma (Carlos)",  steps(FIFTH / 20)),
    ("Harmonic scale (Carlos)", [0, 104.955, 203.910, 297.513, 386.314, 470.781,
                                  551.318, 701.955, 840.528, 905.865, 968.826,
                                  1088.269, 1200.0]),
]
for title, p in carlos:
    deg = len(p) - 1
    walk = deg > 12
    mask = 0 if walk else derive_positions(p, deg)
    entries.append((title, "CARLOS", deg, mask, walk, p))

# --- emit ---------------------------------------------------------------------
maxdeg = max(e[5].__len__() for e in entries)
lines = []
lines.append("/* SPDX-License-Identifier: GPL-3.0-only */")
lines.append("/* GENERATED by tools/gen_muhammad_scales.py from melodee firmware/src/")
lines.append(" * scales.h (+ catalog.json lineage) and the Wendy Carlos scale set.")
lines.append(" * DO NOT EDIT. p[]: cents; p[degrees] = period; mask=chromatic key")
lines.append(" * positions of degrees (walk => no quantization, ALL-style walk). */")
lines.append("#pragma once")
lines.append("#include <cstdint>")
lines.append("")
lines.append("struct StockScale { const char *title; const char *group; int degrees;")
lines.append("                     uint16_t mask; int walk; float p[66]; };")
lines.append("")
lines.append("inline constexpr StockScale P5_STOCK[] = {")
for title, grp, deg, mask, walk, p in entries:
    ps = ", ".join(f"{v:.2f}f" for v in p)
    ps += ", " + ", ".join("0.0f" for _ in range(66 - len(p)))
    lines.append(f'    {{"{title}", "{grp}", {deg}, 0x{mask:03x}, {1 if walk else 0}, {{ {ps} }} }},')
lines.append("};")
lines.append(f"inline constexpr int P5_STOCK_N = {len(entries)};")
lines.append("")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {OUT}: {len(entries)} scales, max period entries {maxdeg}")
