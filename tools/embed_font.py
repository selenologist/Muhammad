#!/usr/bin/env python3
"""Embed the panel font as a C array (src/p5_fontdata.h).
Regenerate with: python3 tools/embed_font.py"""
import pathlib

SRC = pathlib.Path(__file__).resolve().parent.parent
FONTS = [("kFontPanel", "InterTight-Bold.ttf",
          "Inter Tight Bold (wght=700 instance of InterTight[wght].ttf from the "
          "Melodee assets), (c) Rasmus Andersson, SIL OFL 1.1."),
         ("kFontScreen", "VT323-Regular.ttf",
          "VT323 (c) 2011 The VT323 Project Authors, SIL OFL 1.1.")]
out = ["// Generated by tools/embed_font.py — DO NOT EDIT.\n"
       "// Embedded so the panel and the programmer display render identically on\n"
       "// every machine (no font lookup).\n"
       "#pragma once\n#include <cstdint>\n#include <cstddef>\n\nnamespace p5ui {\n\n"]
for name, fn, credit in FONTS:
    data = open(SRC / "assets" / fn, "rb").read()
    out.append(f"// {credit}\n")
    out.append(f"inline constexpr size_t {name}Len = {len(data)};\n")
    out.append(f"inline constexpr uint8_t {name}[{name}Len] = {{\n")
    for i in range(0, len(data), 24):
        out.append(",".join(str(b) for b in data[i:i + 24]) + ",\n")
    out.append("};\n\n")
out.append("} // namespace p5ui\n")
(SRC / "src" / "p5_fontdata.h").write_text("".join(out))
print("wrote src/p5_fontdata.h, fonts:", ", ".join(n for n,_,_ in FONTS))
