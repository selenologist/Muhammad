#!/usr/bin/env python3
"""Snapshot 'Peace Be Upon Him.muhammad' into src/p5_default.hpp.

The embedded array is the boot default for machines WITHOUT the saved file
(CI artifacts, new installs); the live file still wins wherever it exists
(seedDefaultPatch tries the store first). Re-run this after re-recording
the default patch:

    python3 tools/gen_default_hdr.py
"""
import sys, os
SRC = os.path.expanduser("~/Documents/Muhammad Synth/Peace Be Upon Him.muhammad")
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "p5_default.hpp")
data = open(SRC, "rb").read()
if len(data) < 8 + 133 or data[:8] != b"UpMUHAD1":
    sys.exit(f"unexpected patch file {SRC} ({len(data)} bytes)")
raw = data[8:8+133] + b"\x00"          # 134 store bytes; extension byte 0
lines = [", ".join(f"0x{b:02x}" for b in raw[i:i+16]) for i in range(0, 134, 16)]
open(OUT, "w").write(
"""// GENERATED by tools/gen_default_hdr.py - do not edit by hand.
// The recorded boot-default patch: "Peace Be Upon Him" exactly as it was in
// the user's store when embedded. seedDefaultPatch() prefers the live file
// when present and falls back to THESE bytes otherwise, so every platform's
// first load boots the same sound.
#pragma once
#include <cstdint>

namespace pw {

inline constexpr uint8_t PW_DEFAULT_RAW[134] = {
""" + "".join(f"        {l},\n" for l in lines) + """};

} // namespace pw
""")
print("wrote", os.path.relpath(OUT), f"({len(raw)} bytes)")
